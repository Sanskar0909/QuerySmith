-- A small online shop. Five tables, no indexes beyond the ones Postgres
-- creates by itself.
--
-- Worth knowing before you start: PRIMARY KEY creates an index automatically.
-- REFERENCES (a foreign key) does not. So orders.id is indexed and
-- orders.customer_id is not.

CREATE TABLE customers (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       text        NOT NULL,
    full_name   text        NOT NULL,
    created_at  timestamptz NOT NULL
);

CREATE TABLE products (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text    NOT NULL,
    price_cents  integer NOT NULL
);

CREATE TABLE orders (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  bigint      NOT NULL REFERENCES customers (id),
    -- pending -> shipped -> delivered, or cancelled / refunded
    status       text        NOT NULL,
    total_cents  integer     NOT NULL,
    created_at   timestamptz NOT NULL
);

CREATE TABLE order_items (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id          bigint  NOT NULL REFERENCES orders (id),
    product_id        bigint  NOT NULL REFERENCES products (id),
    quantity          integer NOT NULL,
    unit_price_cents  integer NOT NULL
);

CREATE TABLE support_tickets (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  bigint      NOT NULL REFERENCES customers (id),
    -- open or closed
    status       text        NOT NULL,
    subject      text        NOT NULL,
    created_at   timestamptz NOT NULL
);

-- Lab only. Postgres normally refreshes its statistics about a table in the
-- background after the table changes a lot. That is switched off for this one
-- table so that one of the planted problems stays planted.
ALTER TABLE support_tickets SET (autovacuum_enabled = false);
